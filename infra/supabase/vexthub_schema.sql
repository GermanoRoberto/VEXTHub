-- Dynamic monthly partition helper for public.pulses
create or replace function public.ensure_pulse_partition(target_date timestamptz)
returns text
language plpgsql
security definer
as $$
declare
  start_date timestamptz := date_trunc('month', target_date);
  end_date timestamptz := start_date + interval '1 month';
  part_name text := 'pulses_y' || to_char(start_date, 'YYYY') || 'm' || to_char(start_date, 'MM');
  sql_stmt text;
begin
  if not exists (
    select 1
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relname = part_name
  ) then
    sql_stmt := format(
      'create table if not exists public.%I partition of public.pulses for values from (%L) to (%L);',
      part_name,
      to_char(start_date, 'YYYY-MM-DD'),
      to_char(end_date, 'YYYY-MM-DD')
    );
    execute sql_stmt;
  end if;
  return part_name;
end;
$$;


